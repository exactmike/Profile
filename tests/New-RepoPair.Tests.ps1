#requires -Modules @{ ModuleName = 'Pester'; ModuleVersion = '5.0' }

BeforeAll {
    . (Join-Path -Path $PSScriptRoot -ChildPath '..' -AdditionalChildPath 'functions', 'Utilities', 'New-RepoPair.ps1')

    function New-TestRepo {
        param([string]$Name, [hashtable]$TrackedFiles = @{})
        $path = Join-Path -Path $TestDrive -ChildPath $Name
        New-Item -ItemType Directory -Path $path | Out-Null
        git -C $path init --quiet
        git -C $path config user.email 'test@example.invalid'
        git -C $path config user.name 'Test'
        Set-Content -Path (Join-Path -Path $path -ChildPath 'README.md') -Value 'readme'
        foreach ($file in $TrackedFiles.Keys) {
            $target = Join-Path -Path $path -ChildPath $file
            New-Item -ItemType Directory -Path (Split-Path -Path $target -Parent) -Force | Out-Null
            Set-Content -Path $target -Value $TrackedFiles[$file]
        }
        git -C $path add -A
        git -C $path commit --quiet -m 'init'
        $path
    }
}

Describe 'New-RepoPair' -Tag 'UnitTests' {
    Context 'Fresh repo without upstream agent files' {
        BeforeAll {
            $repo = New-TestRepo -Name 'Fresh'
            $local = Join-Path -Path $TestDrive -ChildPath 'local_Fresh'
            $result = New-RepoPair -RepoPath $repo 6>$null
        }

        It 'Returns the expected object' {
            $result.LocalPath | Should -Be $local
            $result.WorkspaceFile | Should -Exist
            $result.NextSteps.Count | Should -BeGreaterThan 0
        }

        It 'Writes the shared instructions and templates in the local repo' {
            Join-Path $local 'AGENTS.md' | Should -FileContentMatch 'repo-pair:v2'
            Join-Path $local 'AGENTS.md' | Should -FileContentMatch '\.\./Fresh'
            (Get-Content -Path (Join-Path $local 'CLAUDE.md') -Raw).Trim() | Should -Be '@AGENTS.md'
            foreach ($name in 'session', 'decision', 'issue', 'pull-request', 'plan') {
                Join-Path $local "templates/$name.md" | Should -Exist
            }
            Join-Path $local 'tools/hooks/Invoke-PairSessionHook.ps1' | Should -Exist
        }

        It 'Writes pointer files for every agent in the code repo' {
            Join-Path $repo 'AGENTS.md' | Should -FileContentMatch '\.\./local_Fresh/AGENTS\.md'
            Join-Path $repo 'AGENTS.override.md' | Should -Not -Exist
            Join-Path $repo '.agents/rules/repo-pair.md' | Should -FileContentMatch 'trigger: always_on'
            Join-Path $repo 'CLAUDE.local.md' | Should -FileContentMatch '^@\.\./local_Fresh/AGENTS\.md'
            Join-Path $repo '.codex/config.toml' | Should -FileContentMatch 'default_permissions = "repo-pair"'
            Join-Path $repo '.codex/hooks.json' | Should -FileContentMatch 'Invoke-PairSessionHook'
        }

        It 'Redirects Claude memory, plans, and directories into the local repo' {
            $settings = Get-Content -Path (Join-Path $repo '.claude/settings.local.json') -Raw | ConvertFrom-Json
            $settings.permissions.additionalDirectories | Should -Contain '../local_Fresh'
            $settings.autoMemoryDirectory | Should -BeLike '*/local_Fresh/memory'
            $settings.plansDirectory | Should -BeLike '*/local_Fresh/plans'
            $settings.hooks.SessionStart[0].hooks[0].command | Should -BeLike '*Invoke-PairSessionHook*SessionStart*'
        }

        It 'Leaves the code repo clean without touching .gitignore' {
            git -C $repo status --porcelain | Should -BeNullOrEmpty
            Join-Path $repo '.gitignore' | Should -Not -Exist
            Join-Path $repo '.git/info/exclude' | Should -FileContentMatch '/CLAUDE\.local\.md'
        }

        It 'Is idempotent on a second run' {
            $second = New-RepoPair -RepoPath $repo 6>$null
            $second.FilesWritten | Should -BeNullOrEmpty
            $excludeLines = Get-Content -Path (Join-Path $repo '.git/info/exclude')
            @($excludeLines | Where-Object { $_ -eq '/AGENTS.md' }).Count | Should -Be 1
        }

        It 'Regenerates changed files with -Force and keeps a backup' {
            Add-Content -Path (Join-Path $local 'AGENTS.md') -Value 'my edit'
            New-RepoPair -RepoPath $repo -Force 6>$null | Out-Null
            Join-Path $local 'AGENTS.md' | Should -Not -FileContentMatch 'my edit'
            (Get-ChildItem -Path $local -Filter 'AGENTS.md.bak-*').Count | Should -Be 1
        }

        It 'Upgrades a Codex config from an earlier version without -Force' {
            $codexConfig = Join-Path $repo '.codex/config.toml'
            Set-Content -Path $codexConfig -Value "# Generated by New-RepoPair.`n[sandbox_workspace_write]`nwritable_roots = ['x']"
            New-RepoPair -RepoPath $repo 6>$null | Out-Null
            $codexConfig | Should -FileContentMatch 'default_permissions = "repo-pair"'
            $codexConfig | Should -Not -FileContentMatch 'sandbox_workspace_write'
            (Get-ChildItem -Path (Join-Path $repo '.codex') -Filter 'config.toml.bak-*').Count | Should -Be 1
            git -C $repo status --porcelain --untracked-files=all | Should -BeNullOrEmpty
        }
    }

    Context 'Repo with an upstream AGENTS.md and a tracked .codex folder' {
        BeforeAll {
            $repo = New-TestRepo -Name 'Upstream' -TrackedFiles @{
                'AGENTS.md'          = 'upstream instructions'
                '.codex/config.toml' = '# upstream codex config'
            }
            $result = New-RepoPair -RepoPath $repo 6>$null
        }

        It 'Does not modify the upstream AGENTS.md' {
            (Get-Content -Path (Join-Path $repo 'AGENTS.md') -Raw).Trim() | Should -Be 'upstream instructions'
        }

        It 'Writes AGENTS.override.md that points at both instruction files' {
            Join-Path $repo 'AGENTS.override.md' | Should -FileContentMatch '\.\./local_Upstream/AGENTS\.md'
            Join-Path $repo 'AGENTS.override.md' | Should -FileContentMatch 'Read `\./AGENTS\.md` in full'
        }

        It 'Imports the upstream AGENTS.md from CLAUDE.local.md' {
            Join-Path $repo 'CLAUDE.local.md' | Should -FileContentMatch '(?m)^@AGENTS\.md'
        }

        It 'Skips the tracked file and reports it' {
            (Get-Content -Path (Join-Path $repo '.codex/config.toml') -Raw).Trim() | Should -Be '# upstream codex config'
            ($result.NextSteps.Step -join "`n") | Should -Match "Skipped '\.codex/config\.toml'"
        }

        It 'Leaves the code repo clean' {
            git -C $repo status --porcelain | Should -BeNullOrEmpty
        }
    }

    Context 'Session hook script' {
        BeforeAll {
            $repo = New-TestRepo -Name 'Hooked'
            $local = Join-Path -Path $TestDrive -ChildPath 'local_Hooked'
            New-RepoPair -RepoPath $repo 6>$null | Out-Null
            $hook = Join-Path $local 'tools/hooks/Invoke-PairSessionHook.ps1'
        }

        It 'Returns a visible notice and model context at SessionStart' {
            $out = '{}' | pwsh -NoProfile -File $hook -Event SessionStart -Agent codex | ConvertFrom-Json
            $out.systemMessage | Should -Match '^\[repo pair\] Instructions: local_Hooked/AGENTS\.md'
            $out.hookSpecificOutput.hookEventName | Should -Be 'SessionStart'
            $out.hookSpecificOutput.additionalContext | Should -Match 'local_Hooked/sessions/\d{4}-\d{2}-\d{2}-codex-'
        }

        It 'Blocks Stop once when no session log exists today' {
            $out = '{"stop_hook_active":false}' | pwsh -NoProfile -File $hook -Event Stop | ConvertFrom-Json
            $out.decision | Should -Be 'block'
            '{"stop_hook_active":true}' | pwsh -NoProfile -File $hook -Event Stop | Should -Be '{}'
        }

        It 'Allows Stop when a session log exists today' {
            Set-Content -Path (Join-Path $local 'sessions/today-claude-test.md') -Value 'log'
            '{}' | pwsh -NoProfile -File $hook -Event Stop | Should -Be '{}'
        }
    }
}
